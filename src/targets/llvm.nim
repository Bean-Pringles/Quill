import std/os
import fileWriter
import tables
import strutils

proc llvmPre*(filename: string) =
    let file = splitFile(filename).name & ".ll"
    
    if fileExists(file):
        try:
            removeFile(file)
        except OSError as e:
            echo "Error deleting file: ", e.msg
    
    writeCode("; LLVM IR generated by Quill Compiler", file)

proc toLLVMType(t: string): string =
    case t
    of "int", "i32":    "i32"
    of "int64", "i64":  "i64"
    of "float", "f32":  "float"
    of "double", "f64": "double"
    of "bool", "i1":    "i1"
    of "string", "ptr": "ptr"
    else:               "i32"

proc llvmPost*(filename: string, vars: Table[string, (string, string, int, bool)], entryCode: seq[string], globalDecls: seq[string], functionDefs: seq[string]) =
    let file = splitFile(filename).name & ".ll"

    for i, decl in globalDecls:
        writeCode(decl, file)
    
    if globalDecls.len > 0:
        writeCode("", file)
    
    for i, funcDef in functionDefs:
        writeCode(funcDef, file)
        if i < functionDefs.len - 1:
            writeCode("", file)
    
    writeCode("", file)
    writeCode("define i32 @_start() {", file)
    writeCode("entry:", file)
        
    for varName, (varType, value, strLen, isCommandResult) in vars.pairs():
        if varType.startsWith("ssa_"):
            continue

        let llvmType = toLLVMType(varType)
            
        if llvmType == "ptr":
            writeCode("  %" & varName & " = alloca ptr, align 8", file)
        else:
            let alignment = case llvmType
                of "i32", "float": "4"
                of "i64", "double": "8"
                of "i1": "1"
                else: "4"
                
            writeCode("  %" & varName & " = alloca " & llvmType & ", align " & alignment, file)
            
            if not isCommandResult:
                writeCode("  store " & llvmType & " " & value & ", ptr %" & varName & ", align " & alignment, file)
        
    for code in entryCode:
        writeCode(code, file)
        
    when defined(windows):
        writeCode("  ret i32 0", file)
    else:
        writeCode("    call void asm sideeffect \"movl $$60, %eax; xorl %edi, %edi; syscall\", \"~{dirflag},~{fpsr},~{flags}\"()", file)
        writeCode("    unreachable", file)
        
    writeCode("}", file)